# Комментарий — для человека. Интерпретатор строку пропускает.

print("Привет")                      # просто текст
print("Аня", 25, "Пермь")            # несколько аргументов через ПРОБЕЛ
print("Аня", 25, sep=", ")           # sep — чем разделять: Аня, 25
print("2026", "09", "12", sep="-")   # 2026-09-12
print("один", end=" ")               # end по умолчанию \n (перевод строки)
print("два")                         # один два  — оба print в одну строку
print()                              # пустая строка
print("A\nB")                        # \n — перевод строки внутри текста
print("колонка\tколонка")            # \t — табуляция

# кавычки ' и " равноправны; внутри текста бери другие
print("он сказал: 'привет'")
print('файл "data.txt"')

