"""Арифметика, цифры числа, f-строки, math."""

print(7 + 3, 7 - 3, 7 * 3)   # 10 4 21
print(7 / 3)                 # 2.333...   / ВСЕГДА float, даже 10/5 → 5.0
print(7 // 3)                # 2          целое деление ВНИЗ
print(7 % 3)                 # 1          остаток
print(7 ** 3)                # 343        степень
print(2 ** 3 ** 2)           # 512        справа налево: 2**(3**2)

print(-7 // 2)               # -4  не -3: «вниз» = к −∞
print(-7 % 2)                # 1

# приёмы без строк
n = 472
print(n % 2 == 0)            # чётное?
print(n % 10)                # последняя цифра  2
print(n // 10)               # без последней    47
print(n // 100)              # сотни            4
print(n // 10 % 10)          # средняя          7

# секунды → ч:мм:сс
total = 3725
h, m, s = total // 3600, total % 3600 // 60, total % 60
print(f"{h}:{m:02d}:{s:02d}")          # 1:02:05

x = 10
x += 1; x -= 2; x *= 3; x //= 2        # сокращённые

print(abs(-5), min(3, 1, 4), max(3, 1, 4), sum([1, 2, 3]))
print(round(3.7), round(3.14159, 2))   # 4  3.14
print(round(2.5), round(3.5))          # 2  4  «к чётному»

print(0.1 + 0.2)                       # 0.30000000000000004
print(0.1 + 0.2 == 0.3)                # False — float приближённый

import math
print(math.pi, math.sqrt(9), math.floor(3.9), math.ceil(3.1))
print(math.floor(-3.1), int(-3.1))     # -4 и -3  — это РАЗНОЕ

# f-строки: f"текст {выражение:формат}"
price = 1234.5678
print(f"{price:.2f}")                  # 1234.57
print(f"{price:.0f}")                  # 1235
print(f"{42:05d}")                     # 00042
print(f"{'товар':<10}{price:>8.2f}")   # выравнивание влево / вправо
print(f"{price=}")                     # отладка: price=1234.5678
