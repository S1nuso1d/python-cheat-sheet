"""Когда list / tuple / dict / set. Одна задача — одна структура."""

#           порядок   меняется   дубли    in (поиск)     типичный случай
# list        да        да        да      медленно      корзина, очередь дел
# tuple       да        нет       да      медленно      точка (x,y), ключ dict
# dict        да*       да     ключи нет   быстро       телефонная книга, счётчик
# set         нет       да        нет      быстро       уникальные теги, пересечение
# * dict с 3.7 помнит порядок добавления

# --- одна и та же идея разными структурами ---
names = ["Аня", "Борис", "Аня"]           # список: порядок и повторы важны
pair = ("Аня", 25)                        # кортеж: ФИО+возраст как одна запись
phone = {"Аня": "123", "Борис": "456"}    # словарь: найти по имени
uniq = {"python", "sql"}                  # множество: «есть ли тег»

print("Аня" in names)                     # перебор списка
print("Аня" in phone)                     # ключ словаря, быстро
print("python" in uniq)                   # множество, быстро

# счётчик: dict, не два списка
cnt = {}
for w in "и раз и два".split():
    cnt[w] = cnt.get(w, 0) + 1

# общие элементы двух списков: set
print(set([1, 2, 3]) & set([2, 3, 9]))    # {2, 3}

# фиксированные поля → tuple или dataclass, не list["имя", 25]
# растущий набор → list
# поиск по имени/id → dict
# «уже видели?» → set
