def unique_keep_order(items):
    """Убрать дубли, сохранив первое вхождение (без set — set теряет порядок)."""
    result = []
    for item in items:
        if item not in result:
            result.append(item)
    return result


def rotate_right(items, k):
    """Циклический сдвиг вправо на k. [1,2,3,4,5], k=2 → [4,5,1,2,3]."""
    if not items:
        return []
    k = k % len(items)          # сдвиг на 7 в списке из 5 = сдвиг на 2
    if k == 0:
        return items.copy()
    return items[-k:] + items[:-k]


def reverse_in_place(items):
    """Развернуть, не создавая новый список (два указателя)."""
    left, right = 0, len(items) - 1
    while left < right:
        items[left], items[right] = items[right], items[left]
        left += 1
        right -= 1
    return items


def second_max(items):
    """Второй по величине за один проход. Нет второго → None."""
    first = second = None
    for value in items:
        if first is None or value > first:
            second, first = first, value
        elif value != first and (second is None or value > second):
            second = value
    return second


print("уникальные:", unique_keep_order([3, 1, 3, 2, 1]))
print("сдвиг:", rotate_right([1, 2, 3, 4, 5], 2))
print("реверс:", reverse_in_place([1, 2, 3, 4, 5]))
print("2-й max:", second_max([3, 7, 2, 9, 4]))


