"""Кортеж (tuple) — как список, но НЕИЗМЕНЯЕМЫЙ. Запись из полей, ключ словаря."""

point = (10, 20)
print(point[0], len(point))
# point[0] = 5                     # TypeError

t = 1, 2, 3                        # скобки необязательны
one = (5,)                         # запятая ОБЯЗАТЕЛЬНА, иначе это int
print(type((5)), type((5,)))       # int  tuple
print(tuple("ab"))                 # ('a', 'b')

# неизменяем сам кортеж, объекты внутри — нет
box = ([1, 2], 3)
box[0].append(4)                   # можно: список внутри
print(box)                         # ([1, 2, 4], 3)

# распаковка
name, age, city = ("Аня", 25, "Пермь")
a, b = 1, 2
a, b = b, a                        # обмен — тоже распаковка
first, *rest = [1, 2, 3, 4]        # first=1, rest=[2,3,4]
first, *mid, last = "abcd"
_, _, city = ("Аня", 25, "Пермь")  # _ = не нужно

print((1, 2) + (3,))               # (1, 2, 3) новый кортеж
print((1, 2) * 2)                  # (1, 2, 1, 2)
print(point.count(10), point.index(20))

# зачем: 1) не сломать запись  2) легче списка  3) можно ключом словаря
board = {(0, 0): "ладья", (7, 7): "король"}
# board[[0, 0]] = "ферзь"          # TypeError: unhashable type: 'list'

# функция «возвращает несколько значений» → на самом деле кортеж
def minmax(xs):
    return min(xs), max(xs)

lo, hi = minmax([3, 1, 9])
print(lo, hi)

# список = растущий набор (корзина)
# кортеж = фиксированная запись (точка, RGB, строка лога)
