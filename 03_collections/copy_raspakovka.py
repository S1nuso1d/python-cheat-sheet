"""Копии и распаковка. Присваивание списка копирует ССЫЛКУ, не данные."""

import copy

a = [1, [2, 3]]
b = a                                  # то же место в памяти
c = a[:]                               # поверхностная копия (как list(a), a.copy())
d = copy.deepcopy(a)                   # полная копия вложенных

a[0] = 99
a[1].append(4)
print("a", a)                          # [99, [2, 3, 4]]
print("b", b)                          # то же
print("c", c)                          # [1, [2, 3, 4]]  внешний свой, внутренний общий
print("d", d)                          # [1, [2, 3]]     полностью своё

# [[0]*3]*3 — три ссылки на ОДИН ряд. Нужно: [[0]*3 for _ in range(3)]

# --- распаковка ---
first, *middle, last = [10, 20, 30, 40]
print(first, middle, last)             # 10 [20, 30] 40

def add(x, y):
    return x + y

print(add(*[2, 3]))                    # распаковать список в аргументы
print({**{"a": 1}, **{"b": 2}})        # слить словари (правый побеждает)
print([1, 2, *[3, 4]])                 # [1, 2, 3, 4]

# zip(*rows) — транспонировать
rows = [(1, "а"), (2, "б")]
print(list(zip(*rows)))                # [(1, 2), ('а', 'б')]
